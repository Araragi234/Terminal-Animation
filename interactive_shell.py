import shlex
import signal
import struct
import sys
import tempfile
import termios
import time
import tty
from pathlib import Path

# Make imports work whether this file is run from the project root or by path.
PROJECT_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(PROJECT_DIR))

from engine.builtin_animations import Starfield
from engine.gif_loader import load_gif
from engine.renderer import detect_background, render_image
from engine.settings import get_default_animation, get_gif_dir

GIF_DIR = get_gif_dir()

PROMPT_MARKER = b"\x1b]777;TA_PROMPT\x07"
FASTFETCH_START_MARKER = b"\x1b]777;TA_FASTFETCH_START\x07"
FASTFETCH_END_MARKER = b"\x1b]777;TA_FASTFETCH_END\x07"
LOGO_WIDTH = 41       # one terminal column wider than the previous 40-column logo
LOGO_HEIGHT = 38      # one terminal row taller (two image pixels per terminal row)
FPS = 25


class MarkerFilter:
    """Split private OSC markers from output while preserving byte order."""

    def __init__(self, markers: dict[bytes, str]):
        self.markers = markers
        self.pending = bytearray()

    def feed(self, data: bytes) -> list[tuple[str, bytes | str]]:
        self.pending.extend(data)
        tokens: list[tuple[str, bytes | str]] = []

        while self.pending:
            matches = []
            for marker, event_name in self.markers.items():
                position = self.pending.find(marker)
                if position >= 0:
                    matches.append((position, marker, event_name))
            if matches:
                position, marker, event_name = min(matches, key=lambda item: item[0])
                if position:
                    tokens.append(("data", bytes(self.pending[:position])))
                del self.pending[:position + len(marker)]
                tokens.append(("event", event_name))
                continue

            keep = 0
            for marker in self.markers:
                maximum = min(len(marker) - 1, len(self.pending))
                for size in range(maximum, 0, -1):
                    if self.pending[-size:] == marker[:size]:
                        keep = max(keep, size)
                        break
            safe_length = len(self.pending) - keep
            if safe_length:
                tokens.append(("data", bytes(self.pending[:safe_length])))
                del self.pending[:safe_length]
            break
        return tokens

    def finish(self) -> list[tuple[str, bytes | str]]:
        if not self.pending:
            return []
        remaining = bytes(self.pending)
        self.pending.clear()
        return [("data", remaining)]



def write_all(fd: int, data: bytes) -> None:
    """Write all bytes, handling partial writes to terminal/PTY descriptors."""
    view = memoryview(data)
    while view:
        written = os.write(fd, view)
        if written <= 0:
            raise OSError("write returned no data")
        view = view[written:]


def terminal_size(fd: int) -> tuple[int, int]:
    packed = fcntl.ioctl(fd, termios.TIOCGWINSZ, b"\0" * 8)
    rows, columns, _, _ = struct.unpack("HHHH", packed)
    return max(1, columns), max(1, rows)


def set_pty_size(master_fd: int, stdin_fd: int) -> None:
    size = fcntl.ioctl(stdin_fd, termios.TIOCGWINSZ, b"\0" * 8)
    fcntl.ioctl(master_fd, termios.TIOCSWINSZ, size)


def make_rcfile() -> str:
    """Source the user's normal Bash config, then install a prompt-ready marker."""
    bashrc = Path.home() / ".bashrc"
    source_line = f"source {shlex.quote(str(bashrc))}" if bashrc.is_file() else ":"
    contents = f"""# Temporary rcfile generated by terminal-animations.
# Set the guard BEFORE sourcing ~/.bashrc so its launcher hook does not recurse.
export TERMINAL_ANIMATIONS_ACTIVE=1
{source_line}
__ta_prompt_marker() {{ printf '\\033]777;TA_PROMPT\\a'; }}
if declare -p PROMPT_COMMAND 2>/dev/null | grep -q '^declare -a'; then
    PROMPT_COMMAND+=(__ta_prompt_marker)
else
    PROMPT_COMMAND="${{PROMPT_COMMAND:+${{PROMPT_COMMAND}}; }}__ta_prompt_marker"
fi
# Wrap later Fastfetch invocations so the controller can move the animation
# to the newly printed logo. The startup invocation has already run above.
fastfetch() {{
    printf '\\033]777;TA_FASTFETCH_START\\007'
    command fastfetch "$@"
    local __ta_status=$?
    printf '\\033]777;TA_FASTFETCH_END\\007'
    return "$__ta_status"
}}
# Bash does not run PROMPT_COMMAND for continuation prompts, so put the same
# invisible marker in PS2 to resume animation while entering multiline input.
PS2="${{PS2-}}> "
PS2="${{PS2}}"$'\\[\\e]777;TA_PROMPT\\a\\]'
"""
    fd, path = tempfile.mkstemp(prefix="terminal-animations-", suffix=".bashrc")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as file:
            file.write(contents)
    except Exception:
        os.unlink(path)
        raise
    return path


def load_animation(background):
    """Load the configured animation, resolving Random separately on each call."""
    setting = get_default_animation() or {"type": "builtin", "identifier": "starfield"}
    animation_type = setting.get("type", "builtin")
    identifier = setting.get("identifier", "starfield")

    if animation_type == "random":
        choices = [("builtin", "starfield")]
        if GIF_DIR.is_dir():
            choices.extend(
                ("gif", str(path.resolve()))
                for path in GIF_DIR.iterdir()
                if path.is_file() and path.suffix.lower() == ".gif"
            )
        animation_type, identifier = random.choice(choices)

    if animation_type == "gif":
        path = Path(identifier).expanduser()
        if path.is_file():
            try:
                frames = load_gif(path, LOGO_WIDTH, LOGO_HEIGHT, background)
                # GIF thumbnails preserve aspect ratio and may be smaller than
                # the logo area. Pad every frame to the full opaque canvas so
                # no fragments of Fastfetch's original logo show around it.
                from PIL import Image

                fitted_frames = []
                for image, duration in frames:
                    canvas = Image.new("RGB", (LOGO_WIDTH, LOGO_HEIGHT), background)
                    left = (LOGO_WIDTH - image.width) // 2
                    top = (LOGO_HEIGHT - image.height) // 2
                    canvas.paste(image, (left, top))
                    fitted_frames.append((canvas, duration))

                return "gif", fitted_frames
            except Exception as error:
                print(f"terminal-animations: couldn't load GIF ({error}); using Starfield", file=sys.stderr)
    return "builtin", Starfield()


def draw_overlay(image, top_row: int, background, terminal_rows: int) -> None:
    """Draw at the Fastfetch logo origin without disturbing Bash's cursor."""
    lines = render_image(image, background)
    # DEC save/restore preserves both cursor position and rendition state.
    output = bytearray(b"\x1b7")
    for index, line in enumerate(lines):
        screen_row = top_row + index
        if screen_row < 0 or screen_row >= terminal_rows:
            continue
        output.extend(f"\x1b[{screen_row + 1};1H".encode())
        output.extend(line.encode("utf-8"))
    output.extend(b"\x1b[0m\x1b8")
    write_all(sys.stdout.fileno(), output)


def erase_overlay(top_row: int, background, terminal_rows: int) -> None:
    """Remove the previous animated logo before a new Fastfetch run."""
    color = f"\x1b[48;2;{background[0]};{background[1]};{background[2]}m".encode()
    blank = b" " * LOGO_WIDTH
    output = bytearray(b"\x1b7")
    for offset in range((LOGO_HEIGHT + 1) // 2):
        screen_row = top_row + offset
        if 0 <= screen_row < terminal_rows:
            output.extend(f"\x1b[{screen_row + 1};1H".encode())
            output.extend(color + blank + b"\x1b[0m")
    output.extend(b"\x1b8")
    write_all(sys.stdout.fileno(), output)


def main() -> int:
    global _resize_pending

    stdin_fd = sys.stdin.fileno()
    stdout_fd = sys.stdout.fileno()

    if not os.isatty(stdin_fd) or not os.isatty(stdout_fd):
        print("Please run interactive_shell.py directly inside a terminal.", file=sys.stderr)
        return 2

    original_settings = termios.tcgetattr(stdin_fd)
    previous_winch_handler = signal.getsignal(signal.SIGWINCH)
    signal.signal(signal.SIGWINCH, _handle_resize)
    rcfile = make_rcfile()
    child_pid = None
    master_fd = None

    prompt_active = False
    animation_started = False
    logo_visible = True
    logo_top = 0
    last_history_count = 0
    screen = None
    stream = None
    decoder = codecs.getincrementaldecoder("utf-8")("replace")
    previous_alt = False

    try:
        # Raw input is needed to receive terminal query responses and forward keys
        # directly to Bash's PTY without the parent terminal doing line editing.
        tty.setraw(stdin_fd)
        background = detect_background(stdin_fd)
        animation_type, animation_data = load_animation(background)
        columns, rows = terminal_size(stdin_fd)

        # pyte tracks the shell's virtual screen and scrollback. A generous history
        # limit lets us move the overlay upward as commands scroll the logo away.
        import pyte
        screen = pyte.HistoryScreen(columns, rows, history=100000)
        stream = pyte.Stream(screen)

        write_all(stdout_fd, b"\x1b[0m\x1b[2J\x1b[H")
        rcfile_path = rcfile
        child_pid, master_fd = pty.fork()

        if child_pid == 0:
            os.execvp("bash", ["bash", "--rcfile", rcfile_path, "-i"])

        set_pty_size(master_fd, stdin_fd)

        marker_filter = MarkerFilter({
            PROMPT_MARKER: "prompt",
            FASTFETCH_START_MARKER: "fastfetch_start",
            FASTFETCH_END_MARKER: "fastfetch_end",
        })
        fastfetch_start_row = 0
        fastfetch_start_history = 0

        # After the first prompt has appeared, these sequences mean the user has
        # deliberately replaced the Fastfetch screen (e.g. running `clear`).
        clear_sequences = (b"\x1b[2J", b"\x1b[H\x1b[2J", b"\x1b[3J")
        alternate_on = (b"\x1b[?1049h", b"\x1b[?47h", b"\x1b[?1047h")
        alternate_off = (b"\x1b[?1049l", b"\x1b[?47l", b"\x1b[?1047l")

        frame_number = 0
        gif_index = 0
        gif_deadline = (time.monotonic() + animation_data[0][1]
                        if animation_type == "gif" else time.monotonic())
        next_frame_time = time.monotonic()
        frame_interval = 1.0 / FPS
        previous_alt = False
        running = True

        def consume_shell_output(raw: bytes) -> None:
            nonlocal logo_visible, last_history_count, logo_top, previous_alt
            nonlocal prompt_active, animation_started
            nonlocal fastfetch_start_row, fastfetch_start_history
            nonlocal animation_type, animation_data, frame_number, gif_index
            nonlocal gif_deadline, next_frame_time

            for token_type, token_value in marker_filter.feed(raw):
                if token_type == "event":
                    event_name = str(token_value)
                    if event_name == "fastfetch_start":
                        if animation_started and logo_visible:
                            _columns, visible_rows = terminal_size(stdin_fd)
                            erase_overlay(logo_top, background, visible_rows)
                        # Re-resolve the saved default for every explicit Fastfetch
                        # invocation. In Random mode this selects a fresh item.
                        animation_type, animation_data = load_animation(background)
                        frame_number = 0
                        gif_index = 0
                        gif_deadline = (time.monotonic() + animation_data[0][1]
                                        if animation_type == "gif" else time.monotonic())
                        next_frame_time = time.monotonic()
                        fastfetch_start_row = screen.cursor.y
                        fastfetch_start_history = len(screen.history.top)
                        prompt_active = False
                        logo_visible = True
                    elif event_name == "fastfetch_end":
                        current_history = len(screen.history.top)
                        scrolled = current_history - fastfetch_start_history
                        logo_top = fastfetch_start_row - max(0, scrolled)
                        last_history_count = current_history
                        logo_visible = True
                    elif event_name == "prompt":
                        prompt_active = True
                        if not animation_started:
                            animation_started = True
                            last_history_count = len(screen.history.top)
                            logo_top = -last_history_count
                    continue

                visible = token_value
                if not isinstance(visible, bytes) or not visible:
                    continue
                stream.feed(decoder.decode(visible))
                if animation_started:
                    history_count = len(screen.history.top)
                    delta = history_count - last_history_count
                    if delta > 0:
                        logo_top -= delta
                    last_history_count = history_count
                write_all(stdout_fd, visible)

                if animation_started:
                    entering_alt = any(sequence in visible for sequence in alternate_on)
                    leaving_alt = any(sequence in visible for sequence in alternate_off)
                    if entering_alt:
                        previous_alt = True
                    if leaving_alt:
                        previous_alt = False
                    if (not previous_alt and not entering_alt and not leaving_alt
                            and any(sequence in visible for sequence in clear_sequences)):
                        logo_visible = False


        while running:
            now = time.monotonic()
            timeout = 0.05
            if prompt_active and logo_visible and not previous_alt:
                timeout = max(0.0, min(timeout, next_frame_time - now))

            readable, _, _ = select.select([stdin_fd, master_fd], [], [], timeout)

            if stdin_fd in readable:
                try:
                    key_data = os.read(stdin_fd, 4096)
                except OSError:
                    key_data = b""

                if not key_data:
                    try:
                        os.write(master_fd, b"\x04")
                    except OSError:
                        pass
                    running = False
                else:
                    # Pause before Bash receives Enter. Readline keystrokes that
                    # do not submit a line leave the animation running.
                    if b"\r" in key_data or b"\n" in key_data:
                        prompt_active = False
                    try:
                        write_all(master_fd, key_data)
                    except OSError:
                        running = False

            if master_fd in readable:
                try:
                    raw = os.read(master_fd, 65536)
                except OSError:
                    raw = b""
                if not raw:
                    running = False
                else:
                    consume_shell_output(raw)

            # Forward terminal resizes to the PTY and update the virtual screen.
            # SIGWINCH is handled via a flag to keep all terminal writes serialized.
            if _resize_pending:
                _resize_pending = False
                try:
                    set_pty_size(master_fd, stdin_fd)
                    new_columns, new_rows = terminal_size(stdin_fd)
                    old_history_count = len(screen.history.top)
                    screen.resize(lines=new_rows, columns=new_columns)
                    new_history_count = len(screen.history.top)
                    if animation_started and new_history_count > old_history_count:
                        logo_top -= new_history_count - old_history_count
                    last_history_count = new_history_count
                except (OSError, ValueError):
                    pass

            now = time.monotonic()
            if (prompt_active and animation_started and logo_visible
                    and not previous_alt and now >= next_frame_time):
                if animation_type == "builtin":
                    image = animation_data.render(
                        LOGO_WIDTH, LOGO_HEIGHT, frame_number, background
                    )
                    frame_number += 1
                else:
                    frames = animation_data
                    if now >= gif_deadline:
                        gif_index = (gif_index + 1) % len(frames)
                        gif_deadline = now + frames[gif_index][1]
                    image, _duration = frames[gif_index]
                if logo_top > -((image.height + 1) // 2):
                    _columns, visible_rows = terminal_size(stdin_fd)
                    draw_overlay(image, logo_top, background, visible_rows)
                else:
                    logo_visible = False
                next_frame_time = now + frame_interval

            # Reap Bash without blocking the animation or input loop.
            if child_pid is not None:
                try:
                    waited, _status = os.waitpid(child_pid, os.WNOHANG)
                except ChildProcessError:
                    waited = child_pid
                if waited == child_pid:
                    child_pid = None
                    running = False

        # Flush any incomplete marker prefix as ordinary shell output.
        for token_type, token_value in marker_filter.finish():
            if token_type == "data" and isinstance(token_value, bytes) and token_value:
                write_all(stdout_fd, token_value)

    finally:
        if child_pid is not None:
            try:
                os.kill(child_pid, signal.SIGHUP)
            except ProcessLookupError:
                pass
            try:
                os.waitpid(child_pid, 0)
            except (ChildProcessError, OSError):
                pass
        if master_fd is not None:
            try:
                os.close(master_fd)
            except OSError:
                pass
        try:
            os.unlink(rcfile)
        except OSError:
            pass
        termios.tcsetattr(stdin_fd, termios.TCSADRAIN, original_settings)
        signal.signal(signal.SIGWINCH, previous_winch_handler)
        write_all(stdout_fd, b"\x1b[0m\x1b[?25h\n")

    return 0


_resize_pending = False


def _handle_resize(signum, frame):
    global _resize_pending
    _resize_pending = True


if __name__ == "__main__":
    raise SystemExit(main())
