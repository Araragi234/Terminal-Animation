"""Bash terminal controller for Fastfetch-linked terminal animations.

The existing Fastfetch line in ~/.bashrc should exec this controller once.
The controller then starts the managed Bash session and wraps later Fastfetch
invocations so each one can reposition the animated logo.
"""

from __future__ import annotations

